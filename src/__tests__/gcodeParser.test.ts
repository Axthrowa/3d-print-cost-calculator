import { describe, expect, it } from 'vitest';
import { gramsFromLength, parseDuration, parseGcode, splitDuration } from '../lib/gcodeParser';

describe('parseDuration', () => {
  it('saat/dakika/saniye kısaltmalarını çözer', () => {
    expect(parseDuration('2h 4m 33s')).toBe(2 * 3600 + 4 * 60 + 33);
    expect(parseDuration('45m')).toBe(2700);
    expect(parseDuration('1d 2h')).toBe(86400 + 7200);
  });

  it('uzun İngilizce yazımı çözer', () => {
    expect(parseDuration('1 hours 23 minutes')).toBe(3600 + 23 * 60);
    expect(parseDuration('45.09 minutes')).toBeCloseTo(2705.4, 6);
  });

  it('saat biçimini çözer', () => {
    expect(parseDuration('01:15:23')).toBe(3600 + 15 * 60 + 23);
    expect(parseDuration('90:30')).toBe(90 * 60 + 30);
  });

  it('düz saniyeyi çözer', () => {
    expect(parseDuration('16320')).toBe(16320);
  });

  it('anlamsız girdide null döner', () => {
    expect(parseDuration('')).toBeNull();
    expect(parseDuration('bilinmiyor')).toBeNull();
  });
});

describe('gramsFromLength', () => {
  it('1.75 mm PLA için doğru gramaj verir', () => {
    // r=0.875mm, V = pi*0.875^2*1000 = 2405.28 mm3 = 2.405 cm3, x1.24 = 2.982 g
    expect(gramsFromLength(1000, 1.75, 1.24)).toBeCloseTo(2.9825, 3);
  });

  it('geçersiz girdide sıfır döner', () => {
    expect(gramsFromLength(0, 1.75, 1.24)).toBe(0);
    expect(gramsFromLength(1000, 0, 1.24)).toBe(0);
    expect(gramsFromLength(1000, 1.75, 0)).toBe(0);
  });
});

describe('splitDuration', () => {
  it('saniyeyi saat ve dakikaya böler', () => {
    expect(splitDuration(16320)).toEqual({ hours: 4, minutes: 32 });
    expect(splitDuration(90)).toEqual({ hours: 0, minutes: 2 });
    expect(splitDuration(0)).toEqual({ hours: 0, minutes: 0 });
    expect(splitDuration(-5)).toEqual({ hours: 0, minutes: 0 });
  });
});

